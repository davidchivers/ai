const fs = require("fs");
const path = require("path");

const {
  BENCHMARK_DEFAULTS,
  EDU_COUNT,
  OUTPUT_ROOT,
  coordinates,
  formatNumber,
  parseArgs,
  parseEntryCutoffs,
  pickScenarioDirectory,
  roundedTickRange,
} = require("./cutoff_figure_utils");

const HUMAN_CAPITAL_LABELS = [
  "Low human-capital",
  "Middle human-capital",
  "High human-capital",
];
const EMPLOYED_COLOR = "tolEmployed";
const UNEMPLOYED_COLOR = "tolUnemployed";
const REGION_FILL_COLOR = "tolRegion";
const REGION_FILL_OPACITY = "0.10";

const DEFAULTS = {
  ...BENCHMARK_DEFAULTS,
  outputFileName: "case147_benchmark_necessity_entry_regions.tex",
  slideOutputFileName: "case147_benchmark_necessity_entry_regions_slide.tex",
  figureLabel: "fig:case147_benchmark_necessity_entry_regions",
  yPadding: 0.15,
  yTickStep: 0.5,
};

function panelTitle(edu) {
  return `${HUMAN_CAPITAL_LABELS[edu]} group`;
}

function addColorDefinitions(lines) {
  lines.push("\\definecolor{tolEmployed}{RGB}{0,68,136}");
  lines.push("\\definecolor{tolUnemployed}{RGB}{187,85,102}");
  lines.push("\\definecolor{tolRegion}{RGB}{187,204,238}");
}

function tikzBody(options) {
  const {
    maxAsset,
    entryCutoffs,
    commonYMin,
    commonYMax,
    yTickStep,
    groupVerticalSep,
    width,
    height,
    includeLegend,
  } = options;

  const lines = [];
  lines.push("\\begin{tikzpicture}");
  lines.push("\\begin{groupplot}[");
  lines.push(`group style={group size=1 by 3, vertical sep=${groupVerticalSep}},`);
  lines.push(`width=${width},`);
  lines.push(`height=${height},`);
  lines.push("xmode=log,");
  lines.push("log basis x={10},");
  lines.push("xmin=0.01,");
  lines.push(`xmax=${formatNumber(maxAsset)},`);
  lines.push("title style={font=\\scriptsize, align=center},");
  lines.push("label style={font=\\scriptsize},");
  lines.push("tick label style={font=\\tiny},");
  lines.push("xtick={0.01,0.1,1,10,40},");
  lines.push("xticklabels={$0.01$,$0.1$,$1$,$10$,$40$},");
  lines.push("axis line style={black!60},");
  lines.push("tick style={black!60},");
  lines.push("tick align=outside,");
  lines.push("]");

  for (let edu = 0; edu < EDU_COUNT; edu += 1) {
    const plotOptions = [
      `title={${panelTitle(edu)}}`,
      "ylabel={critical value $x^*$}",
      edu < EDU_COUNT - 1 ? "xticklabel=\\empty" : "xlabel={asset level $a$}",
      `ymin=${formatNumber(commonYMin)}`,
      `ymax=${formatNumber(commonYMax)}`,
      `ytick distance=${formatNumber(yTickStep)}`,
    ].filter(Boolean);

    lines.push(`\\nextgroupplot[${plotOptions.join(", ")}]`);
    lines.push(
      `\\addplot[name path=emp${edu}, draw=none, const plot] coordinates {${coordinates(
        entryCutoffs.employed[edu]
      )}};`
    );
    lines.push(
      `\\addplot[name path=unemp${edu}, draw=none, const plot] coordinates {${coordinates(
        entryCutoffs.unemployed[edu]
      )}};`
    );
    lines.push(
      `\\addplot[${REGION_FILL_COLOR}, draw=none, fill opacity=${REGION_FILL_OPACITY}] fill between[of=emp${edu} and unemp${edu}];`
    );
    lines.push(
      `\\addplot[${EMPLOYED_COLOR}, thick, const plot, no marks] coordinates {${coordinates(
        entryCutoffs.employed[edu]
      )}};`
    );
    lines.push(
      `\\addplot[${UNEMPLOYED_COLOR}, thick, const plot, no marks] coordinates {${coordinates(
        entryCutoffs.unemployed[edu]
      )}};`
    );
  }

  lines.push("\\end{groupplot}");
  if (includeLegend) {
    lines.push(
      `\\path (current bounding box.south) node[below=0.7cm, align=center, font=\\scriptsize] {\\tikz{\\draw[${EMPLOYED_COLOR}, thick] (0,0) -- (0.45,0);} employed critical value \\quad \\tikz{\\draw[${UNEMPLOYED_COLOR}, thick] (0,0) -- (0.45,0);} unemployed critical value \\quad \\tikz{\\fill[${REGION_FILL_COLOR}, fill opacity=${REGION_FILL_OPACITY}] (0,-0.08) rectangle (0.45,0.08);} necessity-entry region};`
    );
  }
  lines.push("\\end{tikzpicture}");
  return lines.join("\n");
}

function figureBody(options) {
  const { baselineDir, figureLabel } = options;
  const lines = [];
  lines.push("% Auto-generated by generate_case147_benchmark_necessity_entry_regions.js");
  lines.push(`% Baseline source: ${baselineDir.replace(/\\\\/g, "/")}`);
  lines.push("\\begin{figure}[H]");
  lines.push(
    "\\caption{Necessity entrepreneurship by human capital.}"
  );
  lines.push(`\\label{${figureLabel}}`);
  lines.push("\\centering");
  addColorDefinitions(lines);
  lines.push(
    tikzBody({
      ...options,
      groupVerticalSep: "1.1cm",
      width: "0.78\\textwidth",
      height: "0.24\\textwidth",
      titleText: null,
      includeLegend: false,
    })
  );
  lines.push("");
  lines.push("\\vspace{0.2em}");
  lines.push("\\begin{center}");
  lines.push("\\scriptsize");
  lines.push("\\begin{tabular}{@{}ll@{\\hspace{1.5em}}ll@{}}");
  lines.push(
    `\\tikz{\\draw[${EMPLOYED_COLOR}, thick] (0,0) -- (0.45,0);} & employed households & \\tikz{\\draw[${UNEMPLOYED_COLOR}, thick] (0,0) -- (0.45,0);} & unemployed households \\\\`
  );
  lines.push("\\end{tabular}");
  lines.push("\\end{center}");
  lines.push("\\end{figure}");
  lines.push("");
  return lines.join("\n");
}

function slideBody(options) {
  const { baselineDir } = options;
  const lines = [];
  lines.push("% Auto-generated by generate_case147_benchmark_necessity_entry_regions.js");
  lines.push(`% Baseline source: ${baselineDir.replace(/\\\\/g, "/")}`);
  addColorDefinitions(lines);
  lines.push(
    tikzBody({
      ...options,
      groupVerticalSep: "0.7cm",
      width: "0.78\\textwidth",
      height: "0.16\\textwidth",
      titleText: null,
      includeLegend: false,
    })
  );
  lines.push("");
  return lines.join("\n");
}

function main() {
  const cli = parseArgs(process.argv.slice(2));
  const maxAsset = cli["max-asset"] ? Number(cli["max-asset"]) : DEFAULTS.maxAsset;
  const yPadding = cli["y-padding"]
    ? Number(cli["y-padding"])
    : DEFAULTS.yPadding;
  const yTickStep = cli["y-tick-step"]
    ? Number(cli["y-tick-step"])
    : DEFAULTS.yTickStep;

  const baselineDir = pickScenarioDirectory(
    OUTPUT_ROOT,
    cli["baseline-stable-dir"] || DEFAULTS.baselineStableDirName,
    cli["baseline-snapshot-prefix"] || DEFAULTS.baselineSnapshotPrefix,
    cli["baseline-dir"]
  );

  const entryCutoffs = parseEntryCutoffs(
    path.join(baselineDir, "choose_state_next.txt"),
    maxAsset
  );

  const combinedYRange = roundedTickRange(
    [
      ...entryCutoffs.employed,
      ...entryCutoffs.unemployed,
    ],
    yPadding,
    yTickStep
  );
  const commonYMin = cli["y-min"]
    ? Number(cli["y-min"])
    : combinedYRange.min;
  const commonYMax = cli["y-max"]
    ? Number(cli["y-max"])
    : combinedYRange.max;

  const figureText = figureBody({
    baselineDir,
    figureLabel: cli["figure-label"] || DEFAULTS.figureLabel,
    maxAsset,
    entryCutoffs,
    commonYMin,
    commonYMax,
    yTickStep,
  });
  const slideText = slideBody({
    baselineDir,
    maxAsset,
    entryCutoffs,
    commonYMin,
    commonYMax,
    yTickStep,
  });

  const outputFile = path.resolve(__dirname, cli.output || DEFAULTS.outputFileName);
  const slideOutputFile = path.resolve(
    __dirname,
    cli["slide-output"] || DEFAULTS.slideOutputFileName
  );
  fs.writeFileSync(outputFile, figureText, "utf8");
  fs.writeFileSync(slideOutputFile, slideText, "utf8");
  process.stdout.write(`Wrote ${outputFile}\n`);
  process.stdout.write(`Wrote ${slideOutputFile}\n`);
}

main();
