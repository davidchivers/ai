function [path_rows, path_idx] = append_path_rows(path_rows, path_idx, case_spec, alpha, k, results)
start_path = case_spec.guess(:);
final_path = results.final_price_path(:);
implied_path = results.implied_price_path(:);
policy_ref_path = results.policy_reference_price_path_used(:);
Hdemand_path = results.Hdemand_path(:);
Hsupply_path = results.Hsupply_path(:);
excess_path = results.excess_demand_path(:);

for period = 1:k
    path_idx = path_idx + 1;
    path_rows(path_idx) = struct( ...
        'case_name', case_spec.case_name, ...
        'guess_source', case_spec.guess_source, ...
        'alpha', alpha, ...
        'k', k, ...
        'max_iter', case_spec.max_iter, ...
        'period', period, ...
        'start_price', start_path(period), ...
        'final_price', final_path(period), ...
        'implied_price', implied_path(period), ...
        'policy_reference_price_used', policy_ref_path(period), ...
        'Hdemand', Hdemand_path(period), ...
        'Hsupply', Hsupply_path(period), ...
        'excess_demand', excess_path(period));
    end
end

function paths_struct = build_output_paths(this_dir, output_tag)
paths_struct = struct();
paths_struct.summary_path = fullfile(this_dir, sprintf('transition_re_policy_bridge_%s_summary.csv', output_tag));
paths_struct.paths_path = fullfile(this_dir, sprintf('transition_re_policy_bridge_%s_paths.csv', output_tag));
paths_struct.results_path = fullfile(this_dir, sprintf('transition_re_policy_bridge_%s_results.mat', output_tag));
end

function save_partial_outputs(paths_struct, summary_rows, path_rows, all_results, cases, anchor_source, varargin)
summary_table = struct2table(summary_rows);
paths_table = struct2table(path_rows);

writetable(summary_table, paths_struct.summary_path);
writetable(paths_table, paths_struct.paths_path);

save_args = {'summary_table', 'paths_table', 'all_results', 'cases', 'anchor_source'};
if ~isempty(varargin)
    ME = varargin{1}; %#ok<NASGU>
    save_args = [save_args, {'ME'}];
end
save(paths_struct.results_path, save_args{:});
end

function tf = looks_stable(results, params)
tol = 1e-6;
tf = results.update_diagnostics.max_abs_gap < 0.05 && ...
    min(results.final_price_path) > params.fixed_point_price_min + tol && ...
    max(results.final_price_path) < params.fixed_point_price_max - tol;
end

function guess = extend_guess(current_guess, anchor_price_path, k)
guess = current_guess(:);
if numel(guess) >= k
    guess = guess(1:k);
else
    guess = [guess; anchor_price_path(numel(guess) + 1:k)];
end
end

function demographic_path_k = truncate_demographic_path(demographic_path_full, k)
demographic_path_k = demographic_path_full;
fields = fieldnames(demographic_path_full);
for i = 1:numel(fields)
    field_name = fields{i};
    value = demographic_path_full.(field_name);
    if isnumeric(value)
        if isvector(value) && numel(value) == numel(demographic_path_full.periods)
            demographic_path_k.(field_name) = value(1:k, :);
        elseif ismatrix(value) && size(value, 1) == numel(demographic_path_full.periods)
            demographic_path_k.(field_name) = value(1:k, :);
        else
            demographic_path_k.(field_name) = value;
        end
    else
        demographic_path_k.(field_name) = value;
    end
end
demographic_path_k.description = sprintf('%s Truncated to first %d periods for the k=4 warm-start diagnostics.', ...
    demographic_path_full.description, k);
end
