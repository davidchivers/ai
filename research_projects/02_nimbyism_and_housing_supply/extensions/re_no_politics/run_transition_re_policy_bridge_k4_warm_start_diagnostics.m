guess_k3 = extend_guess(state_014.all_results{3, 1}.final_price_path(:), anchor_price_path, 4);
guess_restart_k4 = state_014.all_results{4, 1}.final_price_path(:);
guess_a013_k4 = state_013.all_results{4, 1}.final_price_path(:);
guess_a014_k5_prefix = state_014.all_results{5, 1}.final_price_path(1:4);
guess_a014_k6_prefix = state_014.all_results{6, 1}.final_price_path(1:4);

cases = [ ...
    struct( ...
        'case_name', "default_same_alpha_k3_iter25", ...
        'guess_source', "alpha_0_14_k3_extended_with_anchor_period_4", ...
        'guess', guess_k3, ...
        'max_iter', 25), ...
    struct( ...
        'case_name', "default_same_alpha_k3_iter50", ...
        'guess_source', "alpha_0_14_k3_extended_with_anchor_period_4", ...
        'guess', guess_k3, ...
        'max_iter', 50), ...
    struct( ...
        'case_name', "restart_from_failed_alpha_0_14_k4", ...
        'guess_source', "alpha_0_14_k4_final_price_path", ...
        'guess', guess_restart_k4, ...
        'max_iter', 25), ...
    struct( ...
        'case_name', "restart_from_stable_alpha_0_13_k4", ...
        'guess_source', "alpha_0_13_k4_final_price_path", ...
        'guess', guess_a013_k4, ...
        'max_iter', 25), ...
    struct( ...
        'case_name', "restart_from_alpha_0_14_k5_prefix", ...
        'guess_source', "alpha_0_14_k5_final_price_path_prefix", ...
        'guess', guess_a014_k5_prefix, ...
        'max_iter', 25), ...
    struct( ...
        'case_name', "restart_from_alpha_0_14_k6_prefix", ...
        'guess_source', "alpha_0_14_k6_final_price_path_prefix", ...
        'guess', guess_a014_k6_prefix, ...
        'max_iter', 25) ...
    ];
end

function params = default_diag_params(alpha, max_iter)
params = struct();
params.max_iter = max_iter;
params.tol = 1e-4;
params.damping = 0.25;
params.max_update_frac = 0.10;
params.smoothing_weight = 5.00;
params.terminal_anchor_weight = 0.50;
params.targeted_correction_weight = 0.35;
params.max_targeted_periods = 3;
params.target_block_half_width = 1;
params.line_search_scales = [0.01, 0.02, 0.05];
params.update_scheme = 'sequential_blocks';
params.outer_iteration_mode = 'fertility_style';
params.fixed_point_relaxation_weight = 0.10;
params.fixed_point_relaxation_space = 'log';
params.fixed_point_price_min = 0.40;
params.fixed_point_price_max = 5.00;
params.terminal_price_rule = 'flat_tail';
params.terminal_reference_mode = 'fixed_price';
params.terminal_reference_price = 2.0;
params.transition_policy_mode = 'steady_state_by_period_price';
params.policy_reference_mode = 'blended_current_and_fixed_price';
params.policy_reference_price = 2.0;
params.policy_reference_blend_weight = alpha;
params.policy_reference_price_floor = NaN;
params.policy_reference_price_cap = NaN;
end

function summary_row = build_summary_row(case_spec, alpha, k, results, elapsed_seconds, policy_ref_path)
iter_idx = results.iterations;
final_path = results.final_price_path(:);
implied_path = results.implied_price_path(:);
start_path = case_spec.guess(:);

summary_row = struct( ...
    'case_name', case_spec.case_name, ...
    'guess_source', case_spec.guess_source, ...
    'alpha', alpha, ...
    'k', k, ...
    'max_iter', case_spec.max_iter, ...
    'status', "ok", ...
    'iterations_completed', iter_idx, ...
    'converged', results.converged, ...
    'looks_stable', looks_stable(results, results.params), ...
    'residual_norm', results.iteration_log(iter_idx).residual_norm, ...
    'max_abs_gap', results.update_diagnostics.max_abs_gap, ...
    'max_abs_update', results.iteration_log(iter_idx).max_abs_update, ...
    'accepted_update', string(results.iteration_log(iter_idx).accepted_update), ...
    'worst_gap_period', results.iteration_log(iter_idx).worst_gap_period, ...
    'worst_excess_demand_period', results.iteration_log(iter_idx).worst_excess_demand_period, ...
    'worst_excess_demand', results.iteration_log(iter_idx).worst_excess_demand, ...
    'price_min', min(final_path), ...
    'price_max', max(final_path), ...
    'path_span', max(final_path) - min(final_path), ...
    'policy_reference_price_first_used', policy_ref_path(1), ...
    'policy_reference_price_last_used', policy_ref_path(end), ...
    'elapsed_seconds', elapsed_seconds, ...
    'start_price_1', start_path(1), ...
    'start_price_2', start_path(2), ...
    'start_price_3', start_path(3), ...
    'start_price_4', start_path(4), ...
    'final_price_1', final_path(1), ...
    'final_price_2', final_path(2), ...
    'final_price_3', final_path(3), ...
    'final_price_4', final_path(4), ...
    'implied_price_1', implied_path(1), ...
    'implied_price_2', implied_path(2), ...
    'implied_price_3', implied_path(3), ...
    'implied_price_4', implied_path(4));
end

