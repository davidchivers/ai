function [summary, paths] = run_transition_re_policy_bridge_k4_warm_start_diagnostics(output_tag)
% Diagnose whether the alpha = 0.14, k = 4 instability is a warm-start / basin issue.

if nargin < 1 || isempty(output_tag)
    output_tag = 'k4_warm_start_diagnostics';
end

this_file = mfilename('fullpath');
this_dir = fileparts(this_file);
project_root = fileparts(fileparts(this_dir));
baseline_dir = fullfile(project_root, 'code', 'steadystate');

addpath(baseline_dir);
addpath(this_dir);

demographic_path_full = build_demographic_path_from_age_state_csv(project_root);
demographic_path_k4 = truncate_demographic_path(demographic_path_full, 4);

results_014 = load(fullfile(this_dir, 'transition_re_policy_bridge_alpha_frontier_single_0_14_k6_results.mat'), 'state');
results_013 = load(fullfile(this_dir, 'transition_re_policy_bridge_alpha_frontier_single_0_13_k6_results.mat'), 'state');

state_014 = results_014.state;
state_013 = results_013.state;

anchor_price_path = state_014.anchor_price_path(:);
anchor_source = string(state_014.anchor_source);

alpha = 0.14;
cases = build_case_specs(state_014, state_013, anchor_price_path);

summary_rows = repmat(struct( ...
    'case_name', "", ...
    'guess_source', "", ...
    'alpha', NaN, ...
    'k', NaN, ...
    'max_iter', NaN, ...
    'status', "", ...
    'iterations_completed', NaN, ...
    'converged', false, ...
    'looks_stable', false, ...
    'residual_norm', NaN, ...
    'max_abs_gap', NaN, ...
    'max_abs_update', NaN, ...
    'accepted_update', "", ...
    'worst_gap_period', NaN, ...
    'worst_excess_demand_period', NaN, ...
    'worst_excess_demand', NaN, ...
    'price_min', NaN, ...
    'price_max', NaN, ...
    'path_span', NaN, ...
    'policy_reference_price_first_used', NaN, ...
    'policy_reference_price_last_used', NaN, ...
    'elapsed_seconds', NaN, ...
    'start_price_1', NaN, ...
    'start_price_2', NaN, ...
    'start_price_3', NaN, ...
    'start_price_4', NaN, ...
    'final_price_1', NaN, ...
    'final_price_2', NaN, ...
    'final_price_3', NaN, ...
    'final_price_4', NaN, ...
    'implied_price_1', NaN, ...
    'implied_price_2', NaN, ...
    'implied_price_3', NaN, ...
    'implied_price_4', NaN), numel(cases), 1);

path_rows = repmat(struct( ...
    'case_name', "", ...
    'guess_source', "", ...
    'alpha', NaN, ...
    'k', NaN, ...
    'max_iter', NaN, ...
    'period', NaN, ...
    'start_price', NaN, ...
    'final_price', NaN, ...
    'implied_price', NaN, ...
    'policy_reference_price_used', NaN, ...
    'Hdemand', NaN, ...
    'Hsupply', NaN, ...
    'excess_demand', NaN), numel(cases) * 4, 1);
path_idx = 0;

all_results = cell(numel(cases), 1);
paths_struct = build_output_paths(this_dir, output_tag);

fprintf('=== NIMBY RE policy-bridge k=4 warm-start diagnostics ===\n');
fprintf('Anchor source: %s\n', anchor_source);
fprintf('Target alpha: %.5f\n', alpha);
fprintf('Target horizon: k = 4\n');

for i = 1:numel(cases)
    case_spec = cases(i);
    params = default_diag_params(alpha, case_spec.max_iter);

    fprintf('\nRunning case %s ...\n', case_spec.case_name);
    fprintf('  guess source: %s\n', case_spec.guess_source);
    fprintf('  start path: %s\n', mat2str(case_spec.guess(:)', 6));

    run_tic = tic;
    try
        results = solve_transition_re_no_politics(case_spec.guess, demographic_path_k4, params);
        elapsed_seconds = toc(run_tic);
        all_results{i} = results;

        iter_idx = results.iterations;
        policy_ref_path = results.policy_reference_price_path_used(:);
        summary_rows(i) = build_summary_row(case_spec, alpha, 4, results, elapsed_seconds, policy_ref_path);

        [path_rows, path_idx] = append_path_rows(path_rows, path_idx, case_spec, alpha, 4, results);

        fprintf('  gap=%.6f residual=%.6f range=[%.4f, %.4f] stable=%d\n', ...
            summary_rows(i).max_abs_gap, ...
            summary_rows(i).residual_norm, ...
            summary_rows(i).price_min, ...
            summary_rows(i).price_max, ...
            summary_rows(i).looks_stable);
    catch ME
        elapsed_seconds = toc(run_tic);
        summary_rows(i) = build_error_row(case_spec, alpha, 4, elapsed_seconds);
        save_partial_outputs(paths_struct, summary_rows(1:i), path_rows(1:path_idx), all_results, cases, anchor_source, ME);
        rethrow(ME);
    end

    save_partial_outputs(paths_struct, summary_rows(1:i), path_rows(1:path_idx), all_results, cases, anchor_source);
end

summary = struct2table(summary_rows);
paths = struct2table(path_rows(1:path_idx));

writetable(summary, paths_struct.summary_path);
writetable(paths, paths_struct.paths_path);
save(paths_struct.results_path, 'summary', 'paths', 'all_results', 'cases', 'anchor_source');
end

