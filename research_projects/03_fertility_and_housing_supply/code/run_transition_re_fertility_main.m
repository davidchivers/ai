function path_label = format_path_local(history, prefix, row_idx)
names = history.Properties.VariableNames;
mask = startsWith(names, prefix + "_t");
path_values = history{row_idx, mask};
path_label = format_numeric_path_local(path_values);
end

function path_label = format_numeric_path_local(path_values)
path_values = path_values(:)';
parts = strings(1, numel(path_values));
for i = 1:numel(path_values)
    if isinf(path_values(i))
        parts(i) = "inf";
    else
        parts(i) = sprintf('%.3f', path_values(i));
    end
end
path_label = "[" + strjoin(parts, ", ") + "]";
end

function path_label = format_logical_path_local(path_values)
path_values = logical(path_values(:)');
parts = string(double(path_values));
path_label = "[" + strjoin(parts, ", ") + "]";
end
