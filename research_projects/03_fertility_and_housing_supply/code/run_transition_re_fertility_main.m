function run_transition_re_fertility_main(mode)
% run_transition_re_fertility_main.m
%
% Top-level short-horizon RE smoke driver for the structural five-year
% Bellman transition object.

if nargin < 1 || isempty(mode)
    mode = "smoke";
end
mode = string(mode);

project_root = fileparts(fileparts(mfilename('fullpath')));
out_dir = fullfile(project_root, 'notes', 'build');
if ~exist(out_dir, 'dir')
    mkdir(out_dir);
end

cfg = fertility_benchmark_config();
[initial_q_path, overrides, options, note_suffix] = build_mode_config_local(mode, cfg);

results = solve_transition_re_fertility(initial_q_path, overrides, options);

path_table = table();
summary = results.summary;
if isstruct(summary) && isfield(summary, 'q_path') && ~isempty(summary.q_path)
    T = numel(summary.q_path);
    path_table = table( ...
        (1:T)', ...
        summary.q_path(:), ...
        summary.avg_birth_rate(:), ...
        summary.mean_age_first_birth(:), ...
        summary.owner_share_25_34(:), ...
        summary.mortgaged_owner_share_under_35(:), ...
        summary.total_mass(:), ...
        'VariableNames', {'t', 'q', 'avg_birth_rate', 'mean_age_first_birth', 'owner_share_25_34', 'mortgaged_owner_share_under_35', 'total_mass'});
end

iteration_csv = fullfile(out_dir, sprintf('structural_transition_re_%s_iterations.csv', note_suffix));
vote_csv = fullfile(out_dir, sprintf('structural_transition_re_%s_vote_grid.csv', note_suffix));
period_csv = fullfile(out_dir, sprintf('structural_transition_re_%s_periods.csv', note_suffix));
path_csv = fullfile(out_dir, sprintf('structural_transition_re_%s_path_summary.csv', note_suffix));
note_path = fullfile(out_dir, sprintf('structural_transition_re_%s.md', note_suffix));
mat_path = fullfile(out_dir, sprintf('structural_transition_re_%s_results.mat', note_suffix));

writetable(results.iteration_history, iteration_csv);
writetable(results.vote_grid_history, vote_csv);
writetable(results.period_history, period_csv);
if isempty(path_table)
    if isfile(path_csv)
        delete(path_csv);
    end
else
    writetable(path_table, path_csv);
end
save(mat_path, 'results');
write_note_local(note_path, results, overrides, note_suffix);

disp('Structural transition Bellman RE smoke complete.');
end

